/**
 * 「工具表热刷新」那一行日志的措辞。
 *
 * ## 为什么值得单独一个文件
 *
 * 原来那一行是：
 *
 * ```
 * [daemon] 工具表已热刷新: missing [asr-model] → [无]
 * ```
 *
 * 用户问：「**无 就是没有的意思啊，还是没有工具啊？**」
 *
 * 他读反了，**而且他读反得完全合理**：`after = next.missing.join(',')`，所以
 * `[无]` 的意思是「缺失列表为空」＝**不缺了**，是好消息。可那个「无」被放进了
 * **本该列工具名的那对方括号里** —— 于是它到底修饰「缺失项」还是「工具」，
 * **一个字都没交代**。同一个字符串，两种相反的读法都说得通。
 *
 * ⚠️ 更要紧的是：**cmd 窗口里这些行，对一个双击启动的 Windows 用户来说就是产品的界面。**
 * 它不是"日志"，它是用户唯一能看到的反馈。
 *
 * ## 这一版遵守的规则
 *
 * 1. **状态词绝不进列表位。** 要么给出名字，要么用一整句话说清楚状态 ——
 *    永远不出现「[某个状态词]」这种把状态塞进名字槽的写法。
 * 2. **三个方向都要能说**：装齐了 / 变成缺了 / 还缺几个（中间态）。
 *    原来那一行只有"前 → 后"两个括号，中间态和方向全靠读者自己推。
 * 3. **先说数量再说名字**（`缺 2 项 —— a、b`）。数量为 0 时根本不进这个句式，
 *    改说一句完整的话，所以不可能出现「缺 0 项」这种歧义读法
 *    （`已装 0 个` 与 `缺 0 个` 长得像、意思相反，是同一族里最危险的一种）。
 *
 * 抽成纯函数是为了让**措辞本身变成可断言的性质** —— 与 `ready-banner.ts` 同一个理由。
 * 这也是这一轮唯一做得成的"守卫"：见 `tool-refresh-message.test.ts`。
 */

/** 传进来的是「当前还缺哪些工具」的名字列表（`PipelineBundle.missing`）。 */
export function toolRefreshMessage(before: readonly string[], after: readonly string[]): string {
  const head = '工具表已热刷新：';

  if (after.length === 0) {
    /*
     * 好消息那一支。**这里绝不能只写一个「无」** —— 用户就是在这一支上读反的。
     *
     * ⚠️ 只说**它真的知道的那件事**：四项必需组件都在了。
     *   刻意**不写**「转写可以用了」——`missing` 为空并不严格等价于"能转写"：
     *   引擎与模型格式是否匹配要到 job 运行时才由 `canEngineLoad` 判
     *   （`jobs/runners/transcribe.ts`），而 setup 的 `scanByName` 回退只按扩展名挑。
     *   正常安装路径（有安装记录、带 engine 过滤）不会走到那里，但这条日志
     *   没有资格替它打包票 —— **说得比自己知道的更确定，正是这一整轮在修的病。**
     */
    return `${head}四项必需组件（ffmpeg、ffprobe、whisper-cli、asr-model）都装齐了，当前一项都不缺。`;
  }

  const list = after.join('、');
  if (before.length === 0) {
    // 从"齐了"退回"缺了" —— 这是**变坏**的方向，要说得出它变坏了。
    return `${head}现在缺 ${after.length} 项：${list}（刚才还是齐的）。`;
  }

  // 中间态：仍然缺，但缺的东西变了。前后都给数量与名字，不让读者去比对两个括号。
  return `${head}仍缺 ${after.length} 项：${list}（此前缺 ${before.length} 项：${before.join('、')}）。`;
}
