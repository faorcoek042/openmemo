/**
 * Embedded benchmark audio. ADR-004 decision 3.
 *
 * "Run the benchmark inside the product" needs a clip that is ALWAYS present — a missing
 * asset would turn the one honest number we offer into an error dialog. So the audio is
 * base64 in a source module rather than a file on disk: `tsc` does not copy assets into
 * `dist`, and adding an asset-copy step would mean editing build config this package does
 * not own.
 *
 * Stored as Opus, not WAV. 5 s of 16 kHz mono PCM is 160 KB (213 KB base64); the same
 * audio as Opus @24 kbps is ~15 KB (~20 KB base64) — a 10x saving for a decode step we
 * already have, since ffmpeg is a hard dependency of the pipeline anyway.
 *
 * PROVENANCE (both clips are legally clear for redistribution):
 *   en: Marcus Garvey, speech, 1921 — PUBLIC DOMAIN.
 *       https://commons.wikimedia.org/wiki/File:Marcus_Garvey,_speech,_1921.ogg
 *   zh: Chinese Wikipedia spoken article "Twitter" — CC BY 3.0.
 *       https://commons.wikimedia.org/wiki/File:Zh-Twitter.ogg
 *       Attribution retained here to satisfy the licence.
 *
 * Both are 5.000 s, 16 kHz mono — the exact format every ASR engine we support wants,
 * so a benchmark measures the engine and not our resampling.
 */

