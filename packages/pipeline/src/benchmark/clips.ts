/**
 * Pick the clip matching the model's language.
 *
 * RTF is a compute measurement, so any clip would produce a number — but running a
 * Chinese model over English audio makes the decoder behave unrepresentatively (wrong
 * token distribution, different output length), and the point of this feature is a
 * number the user can trust for THEIR workload.
 */
export function clipForLanguage(language: string | undefined): BenchmarkClip {
  const lang = (language ?? 'en').toLowerCase();
  const zh = BENCHMARK_CLIPS.find((c) => c.id === 'zh');
  const en = BENCHMARK_CLIPS.find((c) => c.id === 'en');
  if (lang.startsWith('zh') || lang.startsWith('cmn') || lang.startsWith('yue')) {
    return zh ?? en!;
  }
  return en ?? zh!;
}
