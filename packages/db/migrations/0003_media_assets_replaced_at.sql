-- ============================================================================
-- 0003_media_assets_replaced_at.sql —— 「这份原件被换掉过」必须留得下痕迹（#96②）
--
-- ## 它对着的那件事
--
-- 网络导入的笔记点「重新转写」，会**重新下载一次源**（那是这个动作的题中之义），
-- 而下载回来的文件落在与上次**完全相同**的路径上，`rename(2)` 把原件**静默覆盖**。
-- 覆盖本身保留 —— 它只发生在重新下载成功之后，用户永远听得到、导得出。
-- 但在这之前，这件事**在库里一个字都没有**：
--   · `media_assets` 这一行的 `uid` / `rel_path` / `created_at` 全不变；
--   · `createAsset` 按 `rel_path` 幂等，第二次调用**原样返回旧行**，
--     于是 `bytes` / `duration_ms` 停在第一次下载时的数（远端内容改了就是错的）；
--   · 表上**没有 `updated_at`**（`notes` / `media_sources` 都有，这张没有），
--     所以连"这一行背后的文件动过"都无处可放。
--
-- 结果是：用户存的那份原件被换成了另一份内容，而**产品从头到尾没提过一个字**。
--
-- ## 为什么是一列时间戳，不是一个布尔
--
-- 布尔只能回答"换过吗"，回答不了"什么时候换的" —— 而用户真正要判断的是
-- "我上次听到的那一版，还在不在"。时间戳能回答，布尔不能。
-- NULL = **从导入到现在，盘上这份文件没被替换过**（不是"不知道"：
-- 写入方只在真的覆盖了一份已存在的文件时才写它）。
--
-- ⚠️ 语义严格限定为「**这个 rel_path 上的文件被一份新取来/新生成的副本覆盖**」，
--    不是「这一行被 UPDATE 过」。本地导入与录音那条路重跑时
--    `archiveIntoMedia` 提前返回、根本不动盘上的文件，那种情况**不写这一列**。
-- ============================================================================

ALTER TABLE media_assets ADD COLUMN replaced_at INTEGER;
